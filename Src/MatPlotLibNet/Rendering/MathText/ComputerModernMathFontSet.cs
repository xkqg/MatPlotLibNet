using System.Collections.Frozen;
using MatPlotLibNet.Styling;

namespace MatPlotLibNet.Rendering.MathText;

/// <summary>matplotlib's <c>'cm'</c> math font set (<c>BakomaFonts</c>), the one its classic style sets math in: the Computer Modern
/// faces of the BaKoMa collection, which code their characters by their place in the TeX fonts. A letter is set in <c>cmmi10</c>
/// (math italic), a digit in <c>cmr10</c>; under a font switch a letter or a digit is set in <c>cmr10</c> (<c>\mathrm</c>), <c>cmb10</c>
/// (<c>\mathbf</c>), <c>cmti10</c> (<c>\mathit</c>) or <c>cmsy10</c> (<c>\mathcal</c>). Every other character is set where matplotlib's
/// <c>latex_to_bakoma</c> table puts it, whatever the switch (<c>\mathbf{\alpha}</c> stays in <c>cmmi10</c>). A character the faces
/// do not hold (<c>\neq</c>, <c>\partial</c>, <c>\mathbb</c>) is set where matplotlib takes it from, in a STIX face
/// (<see cref="StixFallback.ComputerModern"/>).</summary>
/// <remarks>The table of faces and codes (<c>ComputerModernMathFontSet.Data.cs</c>) is generated by
/// <c>tools/mpl_reference/generate_mathtext.py</c>, which parses each character's name with matplotlib 3.11.2's own
/// <c>MathTextParser</c> under <c>mathtext.fontset 'cm'</c> and reads the font and code of the glyph it set.</remarks>
internal sealed partial class ComputerModernMathFontSet() : GlyphMathFontSet(StixFallback.ComputerModern, SizedTable())
{
    private static readonly MathFace Roman = Face("cmr10");
    /// <summary>cmmi10, the math italic, whose letters lean (matplotlib's <c>BakomaFonts</c> reads a glyph of it as slanted).</summary>
    private static readonly MathFace MathItalic = Face("cmmi10") with { Leans = true };
    private static readonly MathFace TextItalic = Face("cmti10");
    private static readonly MathFace Bold = Face("cmb10");
    /// <summary>cmsy10, the math symbols, where the default style's set takes its prime from too.</summary>
    internal static readonly MathFace Symbols = Face("cmsy10");
    internal static readonly MathFace Extension = Face("cmex10") with { RaisesInk = true };
    private static readonly MathFace Typewriter = Face("cmtt10");

    /// <summary>The face and the code of every character Computer Modern holds (generated), made after the faces above.</summary>
    private static readonly FrozenDictionary<char, MathGlyph> Table = TableOfFaces();

    /// <inheritdoc />
    internal override string Name => "cm";

    /// <inheritdoc />
    internal override MathConstants Constants => MathConstants.ComputerModern;

    private static MathFace Face(string family) => new(new Font { Family = family }, CodesByTeX: true);

    /// <inheritdoc />
    private protected override MathGlyph? OwnGlyphOf(char c, FontVariant variant)
    {
        if (char.IsAsciiLetter(c)) return new(LetterFace(variant), c);
        if (char.IsAsciiDigit(c)) return new(DigitFace(variant), c);
        return Table.TryGetValue(c, out var glyph) ? glyph : null;
    }

    /// <summary>The face of a letter under a font switch: math italic without one.</summary>
    private static MathFace LetterFace(FontVariant variant) => variant switch
    {
        FontVariant.Default => MathItalic,
        _ => SwitchedFace(variant),
    };

    /// <summary>The face of a digit under a font switch: roman without one, as TeX sets digits.</summary>
    private static MathFace DigitFace(FontVariant variant) => variant switch
    {
        FontVariant.Default => Roman,
        _ => SwitchedFace(variant),
    };

    /// <summary>The face a font switch sets a letter or a digit in; <c>\mathbb</c> has none here: the fallback table holds every letter
    /// and digit under it and is asked first, so this answer is never read for it.</summary>
    private static MathFace SwitchedFace(FontVariant variant) => variant switch
    {
        FontVariant.Bold => Bold,
        FontVariant.Italic => TextItalic,
        FontVariant.Calligraphic => Symbols,
        _ => Roman,
    };
}