using System.Security.Cryptography;
using System.Text.Json.Nodes;
using MatPlotLibNet.Models;
using MatPlotLibNet.Serialization;
using MatPlotLibNet.Styling;

namespace MatPlotLibNet.Tests.Serialization;

/// <summary>
/// The bytes the PUBLISHED 1.23.0 wrote for a figure with four Y axes (the primary, right slot 0, right slot 1 and left slot 0,
/// each with its own colour, title and one series, and a legend), checked in under <c>Serialization/Compat</c> and read by
/// today's reader. A JSON that was written by a release stays readable for good, so these bytes are fixed: they are not
/// part of <c>MPL_REGEN_GOLDEN</c>'s regeneration set and nothing here writes them.
/// <para>To reproduce the fixture, make a console project that references the MatPlotLibNet 1.23.0 package from nuget.org
/// (<c>&lt;PackageReference Include="MatPlotLibNet" Version="1.23.0" /&gt;</c>, net10.0, implicit usings and nullable on), put
/// this in <c>Program.cs</c> and run it with <c>COMPAT_OUT</c> set to the folder to write to. The data is plain literals, so
/// the bytes do not depend on the platform.</para>
/// <code>
/// using System.Text;
/// using MatPlotLibNet;
/// using MatPlotLibNet.Models;
/// using MatPlotLibNet.Styling;
///
/// string outDir = Environment.GetEnvironmentVariable("COMPAT_OUT") ?? ".";
///
/// var blue = Color.FromHex("#1F77B4");
/// var orange = Color.FromHex("#FF7F0E");
/// var green = Color.FromHex("#2CA02C");
/// var red = Color.FromHex("#D62728");
///
/// Figure figure = Plt.Create()
///     .WithTitle("Four Y axes")
///     .WithSize(900, 500)
///     .AddSubPlot(1, 1, 1, ax => ax
///         .Plot([0.0, 1, 2, 3], [1.0, 3, 2, 4], s => { s.Label = "Primary line"; s.Color = blue; })
///         .SetXLabel("Time")
///         .SetYLabel("Primary")
///         .SetYAxisColor(blue)
///         .WithSecondaryYAxis(y => y
///             .Plot([0.0, 1, 2, 3], [10.0, 30, 20, 40], s => { s.Label = "Right 0 line"; s.Color = orange; })
///             .SetYLabel("Right 0")
///             .SetYAxisColor(orange))
///         .WithOutwardYAxis(AxisSide.Right, y => y
///             .Plot([0.0, 1, 2, 3], [100.0, 300, 200, 400], s => { s.Label = "Right 1 line"; s.Color = green; })
///             .SetYLabel("Right 1"))
///         .WithOutwardYAxis(AxisSide.Left, y => y
///             .Plot([0.0, 1, 2, 3], [0.5, 1.5, 1.0, 2.0], s => { s.Label = "Left 0 line"; s.Color = red; })
///             .SetYLabel("Left 0"))
///         .WithLegend(LegendPosition.UpperLeft))
///     .Build();
///
/// // 1.23.0 has no colour verb on the outward builder: colour those two slots the way the other verbs colour theirs.
/// var axes = figure.SubPlots[0];
/// Colour(axes.RightYAxes[1].Axis, green);
/// Colour(axes.LeftYAxes[0].Axis, red);
///
/// static void Colour(Axis axis, Color color)
/// {
///     axis.MajorTicks = axis.MajorTicks with { Color = color, LabelColor = color };
///     axis.LabelStyle = (axis.LabelStyle ?? new TextStyle()) with { Color = color };
/// }
///
/// File.WriteAllText(Path.Combine(outDir, "v1.23.0-four-axes.json"), figure.ToJson(), new UTF8Encoding(false));
/// File.WriteAllText(Path.Combine(outDir, "v1.23.0-four-axes.svg"), figure.ToSvg().Replace("\r\n", "\n"), new UTF8Encoding(false));
/// </code>
/// <para>The SVG next to the JSON is what 1.23.0 drew for the same figure, kept for comparing a later drawing against it.</para>
/// </summary>
/// <remarks>Tagged into the <c>ChartSerializerGlobalState</c> collection (see <see cref="ChartSerializerGlobalStateCollection"/>):
/// the read goes through the process-global <c>SeriesRegistry</c>.</remarks>
[Collection("ChartSerializerGlobalState")]
public class YAxisContainerWireCompatTests
{
    private static readonly ChartSerializer S = new();

    private static readonly Color Blue = Color.FromHex("#1F77B4");
    private static readonly Color Orange = Color.FromHex("#FF7F0E");
    private static readonly Color Green = Color.FromHex("#2CA02C");
    private static readonly Color Red = Color.FromHex("#D62728");

    /// <summary>The SHA-256 of <c>v1.23.0-four-axes.json</c>, as 1.23.0 wrote it. It makes the fixture a fixed point: a file
    /// regenerated by today's writer, or edited by hand, no longer matches.</summary>
    private const string FixtureSha256 = "C47B701FDBC5AD06A01326B569F4DF38491285F783A7805065DFD3BA9C1845F2";

    private static string FixturePath(string name) =>
        Path.Combine(AppContext.BaseDirectory, "Serialization", "Compat", name);

    private static string FixtureJson() => File.ReadAllText(FixturePath("v1.23.0-four-axes.json"));

    /// <summary>The 1.23.0 bytes are the bytes in the file: a file regenerated by today's writer, or edited by hand, no
    /// longer matches. The frozen fields it was written with are there.</summary>
    [Fact]
    public void AJsonWrittenBy1_23_0_IsPinned()
    {
        string json = FixtureJson();

        Assert.Equal(FixtureSha256, Convert.ToHexString(SHA256.HashData(File.ReadAllBytes(FixturePath("v1.23.0-four-axes.json")))));
        Assert.Contains("\"secondaryYAxis\":{", json, StringComparison.Ordinal);
        Assert.Contains("\"extraRightYAxes\":[{", json, StringComparison.Ordinal);
        Assert.Contains("\"leftYAxes\":[{", json, StringComparison.Ordinal);
    }

    /// <summary>Today's reader puts every axis of the 1.23.0 file where 1.23.0 put it, as a slot of the container: the
    /// primary Y axis is left slot 0, <c>secondaryYAxis</c> right slot 0, the first entry of <c>extraRightYAxes</c> right
    /// slot 1 and the first entry of <c>leftYAxes</c> left slot 1, past the primary, each with its colour, title and
    /// series.</summary>
    [Fact]
    public void AJsonWrittenBy1_23_0_ReadsIntoTheContainer_EverySlotInItsPlace()
    {
        var axes = Assert.Single(S.FromJson(FixtureJson()).SubPlots);

        Assert.Equal(2, axes.YAxes.Left.Count);
        Assert.Equal(2, axes.YAxes.Right.Count);
        Assert.Same(axes.YAxis, axes.YAxes.Left[0].Axis);
        AssertSlot(axes.YAxes.Left[0], "Primary", Blue);
        AssertSlot(axes.YAxes.Right[0], "Right 0", Orange);
        AssertSlot(axes.YAxes.Right[1], "Right 1", Green);
        AssertSlot(axes.YAxes.Left[1], "Left 0", Red);
        Assert.All(axes.YAxes.Right, slot => Assert.Equal(AxisSide.Right, slot.Side));
        Assert.All(axes.YAxes.Left, slot => Assert.Equal(AxisSide.Left, slot.Side));
        Assert.Equal(Blue, axes.Spines.Left.Color);
        Assert.Equal(Orange, axes.Spines.Right.Color);
        Assert.Equal(LegendPosition.UpperLeft, axes.Legend.Position);
    }

    /// <summary>A 1.23.0 file read and written again by today's writer gives the same bytes, so a figure that is read and
    /// saved is not changed on the way, and a 1.23.0 reader still reads what is saved.</summary>
    [Fact]
    public void AJsonWrittenBy1_23_0_RewrittenByTheContainer_IsByteIdentical()
    {
        string json = FixtureJson();

        Assert.Equal(json, S.ToJson(S.FromJson(json)));
    }

    /// <summary>The four axes 1.23.0 wrote, read back, draw what the same figure draws when it is built today with the
    /// container verbs. The comparison is with today's own drawing, never with the SVG 1.23.0 drew: the title gap of 4 px
    /// moved the left titles since.</summary>
    [Fact]
    public void AJsonWrittenBy1_23_0_ReadBack_DrawsTheSameSvgAsTheSameFigureBuiltWithTheNewVerbs()
    {
        Figure built = Plt.Create()
            .WithTitle("Four Y axes")
            .WithSize(900, 500)
            .AddSubPlot(1, 1, 1, ax => ax
                .Plot([0.0, 1, 2, 3], [1.0, 3, 2, 4], s => { s.Label = "Primary line"; s.Color = Blue; })
                .SetXLabel("Time")
                .SetYLabel("Primary")
                .SetYAxisColor(Blue)
                .WithAddRightYAxis(y => y
                    .Plot([0.0, 1, 2, 3], [10.0, 30, 20, 40], s => { s.Label = "Right 0 line"; s.Color = Orange; })
                    .SetYLabel("Right 0")
                    .SetYAxisColor(Orange))
                .WithAddRightYAxis(y => y
                    .Plot([0.0, 1, 2, 3], [100.0, 300, 200, 400], s => { s.Label = "Right 1 line"; s.Color = Green; })
                    .SetYLabel("Right 1")
                    .SetYAxisColor(Green))
                .WithAddLeftYAxis(y => y
                    .Plot([0.0, 1, 2, 3], [0.5, 1.5, 1.0, 2.0], s => { s.Label = "Left 0 line"; s.Color = Red; })
                    .SetYLabel("Left 0")
                    .SetYAxisColor(Red))
                .WithLegend(LegendPosition.UpperLeft))
            .Build();

        string read = S.FromJson(FixtureJson()).ToSvg();

        Assert.Contains(">Left 0<", read, StringComparison.Ordinal);
        Assert.Equal(built.ToSvg(), read);
    }

    private static readonly double[] X = [0.0, 1, 2, 3];

    /// <summary>A figure with the primary Y axis ("P"), <paramref name="right"/> right axes ("R0", "R1", ...) and
    /// <paramref name="left"/> left axes past the primary ("L1", "L2", ...), each with one line named after it and a colour
    /// of its own, added with the container verbs.</summary>
    private static Figure StackedFigure(int right, int left) => Plt.Create().AddSubPlot(1, 1, 1, ax =>
    {
        ax.Plot(X, [1.0, 3, 2, 4], s => s.Label = "P line").SetYLabel("P");
        for (int i = 0; i < right; i++)
        {
            string label = $"R{i}";
            int k = i;
            ax.WithAddRightYAxis(y => y.SetYLabel(label).SetYAxisColor(SlotColour(k)).Plot(X, [k, k + 2.0, k + 1, k + 3], s => s.Label = label + " line"));
        }

        for (int i = 1; i <= left; i++)
        {
            string label = $"L{i}";
            int k = 10 + i;
            ax.WithAddLeftYAxis(y => y.SetYLabel(label).SetYAxisColor(SlotColour(k)).Plot(X, [k, k + 2.0, k + 1, k + 3], s => s.Label = label + " line"));
        }
    }).Build();

    private static Color SlotColour(int k) => new((byte)(30 + 9 * k), (byte)(200 - 7 * k), (byte)(40 + 5 * k));

    /// <summary>The axis labels of a frozen or overflow list in the JSON, in the order written; empty when the field is
    /// absent.</summary>
    private static string?[] LabelsOf(JsonObject axesNode, string field) =>
        axesNode[field] is JsonArray list ? [.. list.Select(entry => (string?)entry!["axis"]!["label"])] : [];

    /// <summary>A 1.23.0 reader reads right slot 0 plus one entry of <c>extraRightYAxes</c>, and one entry of
    /// <c>leftYAxes</c>, and merges every further entry onto the last slot it has. So the frozen fields hold no more than
    /// that, and every slot past it goes into the overflow field of its side, in outward order: every slot has exactly one
    /// carrier, and today's reader reads them all back, each with its own series and colour.</summary>
    [Fact]
    public void AFigureWithFourRightAndThreeLeftAxes_WritesTheFrozenFieldsOnlyUpToTheOldCaps_AndTheRestInTheOverflowFields()
    {
        var figure = StackedFigure(right: 4, left: 3);

        string json = S.ToJson(figure);

        var axesNode = JsonNode.Parse(json)!["subPlots"]![0]!.AsObject();
        Assert.Equal("P", (string?)axesNode["yAxis"]!["label"]);
        Assert.Equal("R0", (string?)axesNode["secondaryYAxis"]!["label"]);
        Assert.Equal(["R1"], LabelsOf(axesNode, "extraRightYAxes"));
        Assert.Equal(["R2", "R3"], LabelsOf(axesNode, "rightYAxesOverflow"));
        Assert.Equal(["L1"], LabelsOf(axesNode, "leftYAxes"));
        Assert.Equal(["L2", "L3"], LabelsOf(axesNode, "leftYAxesOverflow"));

        var axes = Assert.Single(S.FromJson(json).SubPlots);
        Assert.Equal(["R0", "R1", "R2", "R3"], axes.YAxes.Right.Select(slot => slot.Axis.Label));
        Assert.Equal(["P", "L1", "L2", "L3"], axes.YAxes.Left.Select(slot => slot.Axis.Label));
        AssertSameSlots(figure.SubPlots[0].YAxes.Right, axes.YAxes.Right);
        AssertSameSlots(figure.SubPlots[0].YAxes.Left, axes.YAxes.Left);

        Assert.Equal(json, S.ToJson(S.FromJson(json)));
    }

    /// <summary>A figure that stays within what 1.23.0 could hold (two right axes, one left axis past the primary) writes no
    /// overflow field: its bytes are the bytes 1.23.0 wrote for it.</summary>
    [Fact]
    public void AFigureWithinTheOldCaps_WritesNoOverflowField()
    {
        string json = S.ToJson(StackedFigure(right: 2, left: 1));

        Assert.Contains("\"extraRightYAxes\":[{", json, StringComparison.Ordinal);
        Assert.Contains("\"leftYAxes\":[{", json, StringComparison.Ordinal);
        Assert.DoesNotContain("Overflow", json, StringComparison.Ordinal);
    }

    /// <summary>The overflow fields continue the outward order where the frozen field stops: a JSON that carries them is
    /// read slot for slot even when it was written by hand, with right slot 0 created first so no entry moves into it.</summary>
    [Fact]
    public void AnOverflowFieldWithoutTheFrozenFieldsBeforeIt_ReadsPastSlot0_NoneMerged()
    {
        var axesNode = FixtureAxesNode(out var root);
        var right = axesNode["extraRightYAxes"]!;
        var left = axesNode["leftYAxes"]!;
        axesNode.Remove("secondaryYAxis");
        axesNode.Remove("secondarySeries");
        axesNode.Remove("extraRightYAxes");
        axesNode.Remove("leftYAxes");
        axesNode["rightYAxesOverflow"] = new JsonArray(RelabelledSlot(right[0]!, "R1"), RelabelledSlot(right[0]!, "R2"));
        axesNode["leftYAxesOverflow"] = new JsonArray(RelabelledSlot(left[0]!, "L1"), RelabelledSlot(left[0]!, "L2"));

        var axes = Assert.Single(S.FromJson(root.ToJsonString()).SubPlots);

        Assert.Equal([null, "R1", "R2"], axes.YAxes.Right.Select(slot => slot.Axis.Label));
        Assert.Equal(["Primary", "L1", "L2"], axes.YAxes.Left.Select(slot => slot.Axis.Label));
        Assert.Equal(["R1 line", "R2 line"], axes.YAxes.Right.Skip(1).Select(slot => Assert.Single(slot.Series).Label));
        Assert.Equal(["L1 line", "L2 line"], axes.YAxes.Left.Skip(1).Select(slot => Assert.Single(slot.Series).Label));
    }

    /// <summary>The title gap at its default of 4 is left out of the JSON, so a figure that never set it keeps its bytes.</summary>
    [Fact]
    public void AFigureWithTitleGapFour_WritesNoGapField()
    {
        var figure = StackedFigure(right: 1, left: 1);
        figure.SubPlots[0].YAxes.TitleGap = 4;

        Assert.DoesNotContain("yAxisTitleGap", S.ToJson(figure), StringComparison.Ordinal);
    }

    /// <summary>A title gap other than 4 (0 included) is written and read back, and the figure read back draws the same.</summary>
    [Theory]
    [InlineData(9.5)]
    [InlineData(0)]
    public void AFigureWithAnotherTitleGap_RoundTripsIt(double gap)
    {
        var figure = Plt.Create().AddSubPlot(1, 1, 1, ax => ax
            .Plot(X, [1.0, 3, 2, 4]).SetYLabel("P")
            .WithAddRightYAxis(y => y.SetYLabel("R0").Plot(X, [4.0, 3, 2, 1]))
            .WithYAxisTitleGap(gap)).Build();

        string json = S.ToJson(figure);
        var read = S.FromJson(json);

        Assert.Contains(FormattableString.Invariant($"\"yAxisTitleGap\":{gap}"), json, StringComparison.Ordinal);
        Assert.Equal(gap, read.SubPlots[0].YAxes.TitleGap);
        Assert.Equal(figure.ToSvg(), read.ToSvg());
    }

    /// <summary>A title gap in the JSON that is no gap (negative, NaN or infinite) is refused by the name of the field, the
    /// way the verb refuses it, rather than drawn.</summary>
    [Theory]
    [InlineData("-1")]
    [InlineData("\"NaN\"")]
    [InlineData("\"Infinity\"")]
    [InlineData("\"-Infinity\"")]
    public void ABadTitleGapInJson_IsRefused(string gap)
    {
        string json = $$"""{"width":400,"height":300,"subPlots":[{"yAxisTitleGap":{{gap}},"series":[{"type":"line","xData":[1,2],"yData":[1,2]}]}]}""";

        var refusal = Assert.Throws<ArgumentOutOfRangeException>(() => S.FromJson(json));

        Assert.Equal("yAxisTitleGap", refusal.ParamName);
    }

    /// <summary>The 1.23.0 fixture as a node tree, for a test that reshapes the frozen fields the way another writer
    /// could have.</summary>
    private static JsonObject FixtureAxesNode(out JsonNode root)
    {
        root = JsonNode.Parse(File.ReadAllText(FixturePath("v1.23.0-four-axes.json")))!;
        return root["subPlots"]![0]!.AsObject();
    }

    /// <summary>A slot entry of the frozen lists, relabelled: the fixture's first entry with its axis label and series
    /// label set to <paramref name="label"/>.</summary>
    private static JsonNode RelabelledSlot(JsonNode slot, string label)
    {
        var copy = slot.DeepClone();
        copy["axis"]!["label"] = label;
        copy["series"]![0]!["label"] = label + " line";
        return copy;
    }

    /// <summary><c>extraRightYAxes[i]</c> is right slot i + 1 even when the JSON carries no <c>secondaryYAxis</c>: the reader
    /// creates right slot 0 first, as 1.23.0 did, so an extra entry never moves down into slot 0.</summary>
    [Fact]
    public void AJsonWithExtraRightYAxesButNoSecondaryYAxis_KeepsTheOutwardIndexMeaning()
    {
        var axesNode = FixtureAxesNode(out var root);
        axesNode.Remove("secondaryYAxis");
        axesNode.Remove("secondarySeries");

        var axes = Assert.Single(S.FromJson(root.ToJsonString()).SubPlots);

        Assert.Equal(2, axes.YAxes.Right.Count);
        Assert.Null(axes.YAxes.Right[0].Axis.Label);
        Assert.Empty(axes.YAxes.Right[0].Series);
        AssertSlot(axes.YAxes.Right[1], "Right 1", Green);
    }

    /// <summary>The frozen lists are read in full, one slot per entry, with no cap: three extra right entries are right
    /// slots 1 to 3 and two left entries are left slots 1 and 2, past the primary — none merged into another.</summary>
    [Fact]
    public void AFrozenFieldJsonWithThreeExtraRightAxesAndTwoLeft_ReadsEverySlot_NoneMerged()
    {
        var axesNode = FixtureAxesNode(out var root);
        var right = axesNode["extraRightYAxes"]![0]!;
        var left = axesNode["leftYAxes"]![0]!;
        axesNode["extraRightYAxes"] = new JsonArray(RelabelledSlot(right, "R1"), RelabelledSlot(right, "R2"), RelabelledSlot(right, "R3"));
        axesNode["leftYAxes"] = new JsonArray(RelabelledSlot(left, "L0"), RelabelledSlot(left, "L1"));

        var axes = Assert.Single(S.FromJson(root.ToJsonString()).SubPlots);

        Assert.Equal(["Right 0", "R1", "R2", "R3"], axes.YAxes.Right.Select(s => s.Axis.Label));
        Assert.Equal(["Right 0 line", "R1 line", "R2 line", "R3 line"], axes.YAxes.Right.Select(s => Assert.Single(s.Series).Label));
        Assert.Equal(["Primary", "L0", "L1"], axes.YAxes.Left.Select(s => s.Axis.Label));
        Assert.Equal(["Primary line", "L0 line", "L1 line"], axes.YAxes.Left.Select(s => Assert.Single(s.Series).Label));
        AssertSlot(axes.YAxes.Left[0], "Primary", Blue);
    }

    /// <summary>Every slot read back carries the label and colour of the slot written at its place, and its one series.</summary>
    private static void AssertSameSlots(YAxisStack written, YAxisStack read)
    {
        Assert.Equal(written.Count, read.Count);
        for (int i = 0; i < written.Count; i++)
        {
            AssertSlot(read[i], written[i].Axis.Label!, written[i].Axis.MajorTicks.Color);
        }
    }

    /// <summary>The slot's axis carries <paramref name="label"/> and <paramref name="color"/> on its tick marks, tick labels
    /// and title, and the slot holds one series named "<paramref name="label"/> line".</summary>
    private static void AssertSlot(YAxisSlot slot, string label, Color? color)
    {
        Assert.Equal(label, slot.Axis.Label);
        Assert.Equal(color, slot.Axis.MajorTicks.Color);
        Assert.Equal(color, slot.Axis.MajorTicks.LabelColor);
        Assert.Equal(color, slot.Axis.LabelStyle?.Color);
        Assert.Equal(label + " line", Assert.Single(slot.Series).Label);
    }
}
