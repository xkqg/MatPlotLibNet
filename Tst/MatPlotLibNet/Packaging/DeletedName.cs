    /// <summary>Every line of <paramref name="file"/> that names the deleted name, comments included.</summary>
    /// <param name="file">The file to read.</param>
    /// <returns>One finding per line, naming the file, the line and what replaced the name; empty when none names it, or when a published name stands in one of the <see cref="PublishedRecords"/>.</returns>
    public IReadOnlyList<string> MentionsIn(SourceFile file)
    {
        if (Published && PublishedRecords.Contains(file.Path, StringComparer.Ordinal)) return [];

        var pattern = new Regex(@"(?<!\w)" + Regex.Escape(Name) + @"(?!\w)", RegexOptions.CultureInvariant);
        var findings = new List<string>();
        for (int i = 0; i < file.Lines.Count; i++)
        {
            if (pattern.IsMatch(file.Lines[i]))
            {
                findings.Add($"{file.Path}:{i + 1}: names {Name}, which is gone (now {ReplacedBy}): {file.Lines[i].Trim()}");
            }
        }

        return findings;
    }
