        var theme = themeId.AsTheme();
        var figure = FidelityFigure(theme)
            .AddSubPlot(1, 1, 1, ax => ax
                .WithTitle("Filled contour — peaks function")
                .Contourf(x, y, z)
                .WithColorBar())   // the reference's fig.colorbar(cs)
            .Build();

        AssertFidelity(figure, "contour");
    }

